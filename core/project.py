"""
core/project.py
───────────────
Central project state manager.  All agents read from and write to a
ProjectState instance that is serialised to/from project.json.
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


# ─────────────────────────────────────────────────────────────
# Sub-models
# ─────────────────────────────────────────────────────────────

class CharacterBible(BaseModel):
    character_id: str
    name: str
    type: str
    body: str
    height: str
    face: str
    clothing_or_accessories: str
    personality: str
    visual_keywords: List[str] = Field(default_factory=list)
    negative_constraints: List[str] = Field(default_factory=list)
    # Fixed prompt block generated by Character Bible Agent
    prompt_block: str = ""


class LocationBible(BaseModel):
    location_id: str
    name: str
    time_of_day: str
    weather: str
    lighting: str
    color_palette: str
    key_elements: List[str] = Field(default_factory=list)
    style_keywords: List[str] = Field(default_factory=list)
    # Fixed prompt block generated by Environment Bible Agent
    prompt_block: str = ""


class CameraInstruction(BaseModel):
    scene_id: int
    shot_type: str = ""
    camera_angle: str = ""
    camera_movement: str = ""
    lens: str = ""
    lighting: str = ""
    composition: str = ""
    focus: str = ""
    motion_intensity: str = "low"
    motion_score: float = 0.5  # Reverse-engineered stability parameter (0.3 - 0.7)
    camera_vector: Dict[str, float] = Field(default_factory=dict)  # 6DoF: x, y, z, pitch, yaw, roll


class Scene(BaseModel):
    scene_id: int
    duration_seconds: int
    story_beat: str
    emotion: str
    location_id: str
    character_ids: List[str] = Field(default_factory=list)
    camera: Optional[CameraInstruction] = None
    dialogue: str = ""  # Character spoken line embedded in video prompt
    voice_emotion: str = ""  # Spoken delivery cadence and emotional timbre
    audio_cues: str = ""  # Ambient acoustic environment and kinetic spot Foley
    video_prompt: str = ""
    reference_image_path: str = ""
    clip_path: str = ""
    qc_passed: Optional[bool] = None
    qc_score: Optional[int] = None
    qc_issues: List[str] = Field(default_factory=list)
    regeneration_count: int = 0


class AudioPlan(BaseModel):
    music_style: str = ""
    music_bpm: int = 70
    music_mood: str = ""
    voiceover_lines: List[Dict[str, Any]] = Field(default_factory=list)
    sound_effects: List[Dict[str, Any]] = Field(default_factory=list)
    music_path: str = ""
    voiceover_path: str = ""


class DirectorNotes(BaseModel):
    visual_style: str = ""
    camera_style: str = ""
    lighting: str = ""
    editing: str = ""
    music: str = ""
    style_lock: str = ""
    avoid: List[str] = Field(default_factory=list)


class AgentStatus(BaseModel):
    director: bool = False
    story_breakdown: bool = False
    character_bible: bool = False
    environment_bible: bool = False
    reference_images: bool = False
    cinematography: bool = False
    prompt_builder: bool = False
    video_generation: bool = False
    qc: bool = False
    audio: bool = False
    editor: bool = False


# ─────────────────────────────────────────────────────────────
# Main ProjectState
# ─────────────────────────────────────────────────────────────

class ProjectState(BaseModel):
    project_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    project_name: str = "untitled"
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    updated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    # ── Inputs ──────────────────────────────────────────────
    story: str = ""
    target_duration_seconds: int = 30
    platform: str = "instagram_reel"   # instagram_reel | youtube_short | cinematic | ad
    aspect_ratio: str = "9:16"
    style: str = "cinematic"
    tone: str = ""

    # ── Production bibles ────────────────────────────────────
    director_notes: Optional[DirectorNotes] = None
    characters: Dict[str, CharacterBible] = Field(default_factory=dict)
    locations: Dict[str, LocationBible] = Field(default_factory=dict)

    # ── Scenes ───────────────────────────────────────────────
    scenes: List[Scene] = Field(default_factory=list)

    # ── Audio ────────────────────────────────────────────────
    audio_plan: Optional[AudioPlan] = None

    # ── File paths ───────────────────────────────────────────
    project_dir: str = ""
    references_dir: str = ""
    storyboards_dir: str = ""
    clips_dir: str = ""
    audio_dir: str = ""
    output_dir: str = ""
    final_reel_path: str = ""

    # ── Agent completion tracking ────────────────────────────
    agents: AgentStatus = Field(default_factory=AgentStatus)

    # ─────────────────────────────────────────────────────────
    # Helpers
    # ─────────────────────────────────────────────────────────

    def get_character(self, character_id: str) -> Optional[CharacterBible]:
        return self.characters.get(character_id)

    def get_location(self, location_id: str) -> Optional[LocationBible]:
        return self.locations.get(location_id)

    def get_scene(self, scene_id: int) -> Optional[Scene]:
        for s in self.scenes:
            if s.scene_id == scene_id:
                return s
        return None

    def all_clips_generated(self) -> bool:
        return all(bool(s.clip_path) for s in self.scenes)

    def all_clips_qc_passed(self) -> bool:
        return all(s.qc_passed for s in self.scenes)

    def touch(self) -> None:
        self.updated_at = datetime.now(timezone.utc).isoformat()

    # ─────────────────────────────────────────────────────────
    # Persistence
    # ─────────────────────────────────────────────────────────

    def save(self, path: Optional[str] = None) -> Path:
        self.touch()
        target = Path(path) if path else Path(self.project_dir) / "project.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            self.model_dump_json(indent=2), encoding="utf-8"
        )
        return target

    @classmethod
    def load(cls, path: str | Path) -> "ProjectState":
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls(**data)

    @classmethod
    def create(
        cls,
        project_name: str,
        story: str,
        base_dir: str | Path,
        *,
        duration: int = 30,
        platform: str = "instagram_reel",
        aspect_ratio: Optional[str] = None,
        style: str = "cinematic",
        tone: str = "",
    ) -> "ProjectState":
        """Create a new project and initialise its directory structure."""
        base = Path(base_dir)
        project_dir = base / "projects" / project_name
        project_dir.mkdir(parents=True, exist_ok=True)

        dirs = {
            "references": project_dir / "references",
            "storyboards": project_dir / "storyboards",
            "clips": project_dir / "clips",
            "audio": project_dir / "audio",
            "output": project_dir / "output",
        }
        for d in dirs.values():
            d.mkdir(parents=True, exist_ok=True)

        if not aspect_ratio:
            aspect_ratio = "16:9" if (platform in ["cinematic", "youtube", "widescreen"] or "16:9" in platform) else "9:16"

        state = cls(
            project_name=project_name,
            story=story,
            target_duration_seconds=duration,
            platform=platform,
            aspect_ratio=aspect_ratio,
            style=style,
            tone=tone,
            project_dir=str(project_dir),
            references_dir=str(dirs["references"]),
            storyboards_dir=str(dirs["storyboards"]),
            clips_dir=str(dirs["clips"]),
            audio_dir=str(dirs["audio"]),
            output_dir=str(dirs["output"]),
        )

        # Save initial story.txt alongside project.json
        (project_dir / "story.txt").write_text(story, encoding="utf-8")
        state.save(str(project_dir / "project.json"))
        return state
